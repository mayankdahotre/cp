void solve() {
    int n;
    cin>>n;

    vector<int> a(n), b(n);
    for(int i=0; i<n; i++) cin>>a[i];
    for(int i=0; i<n; i++) cin>>b[i];

    int aj=0, mai=0;
    for(int i=0; i<n; i++){
        if(i%2 && a[i]!=b[i]) mai++;
        else if(i%2==0 && a[i]!=b[i]) aj++;
    }

    if(aj>mai) cout<<"Ajisai"<<endl;
    else if(mai>aj) cout<<"Mai"<<endl;
    else cout<<"Tie"<<endl;

    return;
}

