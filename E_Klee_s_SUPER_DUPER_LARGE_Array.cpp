int f(int n, int k, int i){
    return abs((i*(i+1) + 2*k*(i+1)) - (n*(n-1)/2 + k*n));
}

void solve() {
    int n,k;
    cin>>n>>k;

    int l=0, r=n-1;
    while(r-l>2){
        int m1 = l+(r-l)/3;
        int m2 = r-(r-l)/3;

        if(f(n,k,m1)<f(n,k,m2)) r=m2-1;
        else l=m1+1;
    }

    int mn=f(n,k,l);
    for(int i=l+1; i<=r; i++) mn=min(mn, f(n,k,i));

    cout<<mn<<endl;
    return;
}

int32_t main() {
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int T;
    cin >> T;

    while (T--) {
        solve();
    }

    return 0;
}