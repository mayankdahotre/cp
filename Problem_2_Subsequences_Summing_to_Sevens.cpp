void solve() {
    int n;
    cin>>n;

    vector<int> v(n);
    for(int i=0; i<n; i++) cin>>v[i];

    int x=7;
    vector<int> mod(x,0);
    mod[0]=1;

    for(int i=0; i<n; i++){
        int k=((v[i]%x)+x)%x;
        mod[k]++;
    }

    int ans=mod[0];
    for(int i=1; i<x; i++){
        ans=max(ans, min(mod[i],mod[x-i]));
    }

    cout<<ans<<endl;
    return;
}

int32_t main() {
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    solve();

    return 0;
}