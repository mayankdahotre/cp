#define yes cout << "YES\n"
#define no cout << "NO\n"

void solve() {
    int n,m;
    cin>>n>>m;

    vector<string> v(n);
    for(int i=0; i<n; i++) cin>>v[i];

    vector<int> ch(26,0);
    for(int i=0; i<n; i++) ch[v[i][0]-'a']=1;

    bool ok=true;
    while(m--){
        string s;
        cin>>s;

        for(int i=0; i<s.length(); i++){
            if(!ch[s[i]-'A']){
                ok=false;
            }
        }
    }

    if(ok) yes;
    else no;
}

int32_t main() {
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int T;
    cin >> T;

    while (T--) {
        solve();
    }

    return 0;
}