void solve() {
    int n;
    cin>>n;

    int ans = (2*n+2)/3; 
    int k = n%3;

    ans += (n+1)/2;

    if(k==1) if(n%2!=0) ans--; 
    else if (k==2) if(n%2==0) ans++;

    if(n==1) ans++;

    cout<<ans<<endl;
    return;
}

