void solve() {
    int x,y,k;
    cin>>x>>y>>k;

    while(k){
        int r = y-x%y;
        if(k>=r){
            k-=r;
            while((x+y-1)%y==0) x=(x+y-1)/y;
        }
    }

    cout<<x<<endl;
    return;
}

