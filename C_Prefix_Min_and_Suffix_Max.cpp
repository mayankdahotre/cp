void solve() {
    int n;
    cin >> n;

    vector<int> v(n);
    for (int i = 0; i < n; i++) cin >> v[i];

    string s = string(n, '0');

    vector<int> premn(n), sufmx(n);
    
    premn[0] = v[0];
    for (int i = 1; i < n; i++) premn[i] = min(premn[i - 1], v[i]);

    sufmx[n - 1] = v[n - 1];
    for (int i = n - 2; i >= 0; i--) sufmx[i] = max(sufmx[i + 1], v[i]);

    for (int i = 0; i < n; i++) {
        if (v[i] == premn[i] || v[i] == sufmx[i]) {
            s[i] = '1';
        }
    }

    cout << s << endl;
    return;
}

int32_t main() {
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int T;
    cin >> T;

    while (T--) {
        solve();
    }

    return 0;
}