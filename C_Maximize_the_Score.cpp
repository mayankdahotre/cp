void solve() {
    int n;
    cin>>n;

    vector<int> v(n);
    for(int i=0; i<n; i++) cin>>v[i];

    int ans=0;
    while(v.size()){
        map<int, vector<int>> mp;
        for(int i=0; i<n; i++) mp[v[i]].push_back(i);

        int a=-1, b=-1, x=0;

        for(auto p: mp){
            int l = p.second[0];
            int r = p.second.back();

            if(x<r-l+1){
                a=l,
                b=r;
                x=max(x,r-l+1);
            }
        }

        vector<int> v2;
        for(int i=0; i<a-1; i++) v2.push_back(v[i]);
        for(int i=b; i<n; i++) v2.push_back(v[i]);

        v=v2;

        ans+=x*x;
    }

    cout<<ans<<endl;
    return;
}

int32_t main() {
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int T;
    cin >> T;

    while (T--) {
        solve();
    }

    return 0;
}