void solve() {
    int n,k;
    cin>>n>>k;

    vector<int> v(n);
    
    int x=1;
    for(int i=0; i<k; i+=2){
        for(int j=i; j<n; j+=k){
            v[j]=x;
            x++;
        }
    }

    x=n;
    for(int i=1; i<k; i+=2){
        for(int j=i; j<n; j+=k){
            v[j]=x;
            x--;
        }
    }

    for(int i=0; i<n; i++) cout<<v[i]<<" ";
    cout<<endl;

    return;
}

int32_t main() {
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int T;
    cin >> T;

    while (T--) {
        solve();
    }

    return 0;
}