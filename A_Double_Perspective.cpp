void solve() {
    int n;
    cin>>n;

    vector<pair<int,int>> vp;
    for(int i=0; i<n; i++) cin>>vp[i].first>>vp[i].second;

    map<int,int> mp;
    vector<int> vis(n,1);
    for(int i=0; i<n; i++){
        if(mp.find(vp[i].first) && mp.find(vp[i].second)) vis[i]=0;
        mp[vp[i].first]=1;
        mp[vp[i].second]=1;
    }

    for(int i=0; i<n; i++) if(vis[i]) cout<<i+1<<" ";
    cout<<endl;

    return;
}

int32_t main() {
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int T;
    cin >> T;

    while (T--) {
        solve();
    }

    return 0;
}