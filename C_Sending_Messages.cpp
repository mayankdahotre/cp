#define yes cout << "YES\n"
#define no cout << "NO\n"

void solve() {
    int n,f,a,b;
    cin>>n>>f>>a>>b;

    vector<int> v(n);
    for(int i=0; i<n; i++) cin>>v[i];

    int x=min(b, a*v[0]);
    for(int i=0; i<n-1; i++) x+=min(b, (v[i+1]-v[i])*a);
    
    if(x<f) yes;
    else no;

    return;
}

int32_t main() {
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int T;
    cin >> T;

    while (T--) {
        solve();
    }

    return 0;
}