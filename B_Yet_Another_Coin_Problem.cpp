void solve() {
    int n;
    cin>>n;

    int ans=0;
    vector<int> v = {15,10,6,3,1};
    for(auto i: v){
        ans+=n/i;
        n=n%i;
    }

    cout<<ans<<endl;
    return;
}

int32_t main() {
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int T;
    cin >> T;

    while (T--) {
        solve();
    }

    return 0;
}