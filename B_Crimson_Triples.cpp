void solve() {
    int n;
    cin >> n;

    int ans = 0;

    for (int b = 1; b <= n; b++) {
        int cnt = n / b;
        ans += cnt * cnt;
    }

    cout << ans << endl;
    return;
}

int32_t main() {
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int T;
    cin >> T;

    while (T--) {
        solve();
    }

    return 0;
}