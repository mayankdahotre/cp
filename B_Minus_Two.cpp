void solve() {
    int n;
    cin>>n;

    vector<int> v(n);
    for(int i=0; i<n; i++) cin>>v[i];

    int o=0, e1=0, e2=0;
    for(int i=0; i<n; i++){
        if(v[i]%2) o++;
        else if(v[i]%4==2) e1++;
        else if(v[i]%4==0) e2++;
    }

    int ans=max(o, max(e1,e2));

    cout<<ans<<endl;
    return;
}

int32_t main() {
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int T;
    cin >> T;

    while (T--) {
        solve();
    }

    return 0;
}