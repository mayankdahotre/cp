#define yes cout << "YES\n"
#define no cout << "NO\n"

void solve() {
    vector<int> v(3);
    for(int i=0; i<3; i++) cin>>v[i];

    sort(v.begin(), v.end());

    if (v[0]==5 && v[1]==5 && v[2]==7) yes;
    else no;

    return;
}

