void solve() {
    int n;
    cin>>n;

    vector<int> v(n);
    for(int i=0; i<n; i++) cin>>v[i];

    sort(v.begin(), v.end());
    
    int mex=0;
    for(int i=0; i<n; i++) if(v[i]==mex) mex++;

    vector<int> f(mex + 1, 0); 
    for(int i=0; i<n; i++) if(v[i] < mex) f[v[i]]++;

    vector<int> d(n + 3, 0); 
    for(int k=0; k<=mex; k++){
        d[f[k]]++;     
        d[n-k+1]--;
        if(!f[k]) break;
    }

    for(int i=1; i<=n; i++) d[i]+=d[i-1];

    for(int i=0; i<=n; i++) cout<<d[i]<<" "; 
    cout<<endl;

    return;
}

int32_t main() {
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int T;
    cin >> T;

    while (T--) {
        solve();
    }

    return 0;
}