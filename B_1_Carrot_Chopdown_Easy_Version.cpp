void solve() {
    int n,m;
    cin>>n>>m;

    vector<int> v(n);
    map<int,int> mp;
    for(int i=0; i<n; i++){
        cin>>v[i];
        mp[v[i]]++;
    }

    sort(v.begin(), v.end());

    int a=0;
    for(int i=1; i<=m; i++){
        auto j=upper_bound(v.begin(), v.end(), i);
        int k=v.end()-j;
        a=max(a, mp[i]+k+mp[2*i]);
    }

    cout<<a<<endl;
    return;
}

int32_t main() {
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int T;
    cin >> T;

    while (T--) {
        solve();
    }

    return 0;
}