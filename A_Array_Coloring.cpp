#define yes cout << "YES\n"
#define no cout << "NO\n"

bool cmp(pair<int,int> a, pair<int,int> b){
    return a.first<b.first;
}

void solve() {
    int n;
    cin>>n;

    vector<pair<int,int>> v(n);
    for(int i=0; i<n; i++){
        cin>>v[i].first;
        v[i].second=i%2;
    }

    sort(v.begin(), v.end(), cmp);

    for(int i=0; i<n-1; i++){
        if(v[i].second==v[i+1].second){
            no;
            return;
        }
    }

    yes;
    return;
}

int32_t main() {
    ios_base::sync_with_stdio(false);
    cin.tie(NULL);
    cout.tie(NULL);

    int T;
    cin >> T;

    while (T--) {
        solve();
    }

    return 0;
}